-- Special-workspace scratchpads: what launches in them, and how they look.
--
-- These are `on_created_empty` rules, so the command runs the first time the
-- scratchpad is summoned and never again — the session persists across toggles.
-- Bound to SUPER+S / SUPER+Y / SUPER+B in modules/keybinds.lua.

local terminal = require("lib.terminal")

-- zellij sessions: ONE special workspace (SUPER+S) holding a window GROUP, one tab
-- per host. The groupbar on top labels each tab, and each server keeps its own
-- border colour and kitty palette. This replaced the separate special:jjserver
-- scratchpad (SUPER+A, now unbound) on 2026-10-07.
--
-- Tabs, in launch order:
--   local     this machine, session `main`, normal theme.
--   jjserver  kitten ssh, session `jjserver`, macchiato palette.
--   pve-prod  kitten ssh, session `pve-prod`, ember palette (VM 110 on pve).
-- A server's palette is set in scripts/server-theme/hosts.conf and pushed with
-- `scripts/server-theme/deploy.sh <label>`. That writes the kitty theme that
-- kitty/<label>.conf includes, and theme/<label>.lua with the border colour.
-- kitty/<label>.conf re-pins that theme after the wallpaper include, so a live
-- theme reload (SIGUSR1) keeps the server palette.
--
-- Each window gets kitty --class zellij-<label>, so the rules below can tell
-- them apart. --title fixes the tab label. Without it the labels were the titles
-- zellij and kitten set ("zellij", "kitten"), which name no host. Hardcoded to
-- kitty (not lib.terminal) because --class, --title, --config and the ssh kitten
-- are kitty-specific.
--
-- Closing a window only detaches its zellij client. The sessions keep running.
--
-- Launch order matters: the local window makes the group (`group = "set always"`)
-- and gets focus. Each server window then joins the FOCUSED group through
-- group.auto_group (default on). A server window that opened first would find no
-- group to join, so each one starts 1 s after the one before.
-- `group = "invade"` does NOT do this: tested 2026-10-07, a pve-prod window with
-- that rule opened beside the group, not in it, while the group had no focus.
local servers = {
	{ label = "jjserver", target = "jjserver@100.68.211.32" },
	{ label = "pve-prod", target = "pve-prod-ts" },
}

local launch = "kitty --class zellij-local --title local zellij attach main --create"
for i, srv in ipairs(servers) do
	launch = launch
		.. " & sleep " .. i .. "; kitty --class zellij-" .. srv.label
		.. " --title " .. srv.label
		.. " --config ~/.config/kitty/" .. srv.label .. ".conf"
		.. " kitten ssh -t " .. srv.target .. " zellij attach " .. srv.label .. " --create"
end

hl.workspace_rule({
	workspace = "special:zellij",
	on_created_empty = "sh -c '" .. launch .. "'",
})

hl.window_rule({
	name = "zellij-local-group",
	match = { class = "^zellij-local$" },
	workspace = "special:zellij silent",
	group = "set always",
})

for _, srv in ipairs(servers) do
	local class = "^zellij-" .. srv.label .. "$"
	hl.window_rule({
		name = "zellij-" .. srv.label .. "-group",
		match = { class = class },
		workspace = "special:zellij silent",
	})

	-- Border in the server palette primary, from theme/<label>.lua (generated by
	-- deploy.sh). pcall so a host without the generated file still loads cleanly.
	local ok, colors = pcall(require, "theme." .. srv.label)
	if ok and type(colors) == "table" and colors.primary then
		local c = "rgb(" .. colors.primary .. ")"
		hl.window_rule({
			name = srv.label .. "-border",
			match = { class = class },
			border_color = c .. " " .. c,
		})
	end
end

